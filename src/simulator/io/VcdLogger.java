package simulator.io;

import simulator.core.SignalObserver;
import simulator.core.VoltageState;
import simulator.core.Wire;
import simulator.engine.SimulationContext;

import java.io.FileWriter;
import java.io.IOException;
import java.io.PrintWriter;
import java.io.StringWriter;
import java.util.ArrayList;
import java.util.IdentityHashMap;
import java.util.List;
import java.util.Map;

public class VcdLogger implements SignalObserver {
    private final String filepath;
    private final SimulationContext simulationContext;
    private final List<Wire> monitoredWires;
    private final Map<Wire, String> identifiers;
    private final List<String> transitionBuffer;

    public VcdLogger(String filepath) {
        this(filepath, SimulationContext.defaultContext());
    }

    public VcdLogger(String filepath, SimulationContext simulationContext) {
        if (simulationContext == null) {
            throw new IllegalArgumentException("Simulation context cannot be null");
        }
        this.filepath = filepath;
        this.simulationContext = simulationContext;
        this.monitoredWires = new ArrayList<>();
        this.identifiers = new IdentityHashMap<>();
        this.transitionBuffer = new ArrayList<>();
    }

    public void monitorWire(Wire wire) {
        if (!identifiers.containsKey(wire)) {
            identifiers.put(wire, createIdentifier(monitoredWires.size()));
            monitoredWires.add(wire);
            wire.addObserver(this);
        }
    }

    @Override
    public void update(Wire source, VoltageState newState) {
        long currentTime = simulationContext.getEventEngine().getCurrentTime();
        transitionBuffer.add("#" + currentTime);
        transitionBuffer.add(formatState(newState) + identifiers.get(source));
    }

    private String formatState(VoltageState state) {
        switch (state) {
            case HIGH: return "1";
            case LOW: return "0";
            case HIGH_Z: return "z";
            default: return "x";
        }
    }

    public void exportFile() throws IOException {
        try (PrintWriter writer = new PrintWriter(new FileWriter(filepath))) {
            writer.print(toVcd());
        }
    }

    public String toVcd() {
        StringWriter buffer = new StringWriter();
        PrintWriter writer = new PrintWriter(buffer);
        writer.println("$date Generated by DigitalCircuitSimulator $end");
        writer.println("$version DigitalCircuitSimulator $end");
        writer.println("$timescale 1ns $end");
        writer.println("$scope module logic $end");
        for (Wire wire : monitoredWires) {
            String identifier = identifiers.get(wire);
            writer.println("$var wire 1 " + identifier + " " + wire.getWireId() + " $end");
        }
        writer.println("$upscope $end");
        writer.println("$enddefinitions $end");
        writer.println("$dumpvars");
        for (Wire wire : monitoredWires) {
            writer.println(formatState(wire.getCurrentState()) + identifiers.get(wire));
        }
        writer.println("$end");
        writer.println("#0");
        for (String transition : transitionBuffer) {
            writer.println(transition);
        }
        writer.flush();
        return buffer.toString();
    }

    private static String createIdentifier(int index) {
        StringBuilder identifier = new StringBuilder();
        int value = index;
        do {
            identifier.append((char) ('!' + value % 94));
            value = value / 94 - 1;
        } while (value >= 0);
        return identifier.reverse().toString();
    }
}
